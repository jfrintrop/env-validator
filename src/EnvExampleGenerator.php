<?php

declare(strict_types=1);

namespace Jfrintrop\EnvValidator;

/**
 * Turns a validation schema into the contents of a `.env.example` file:
 * one entry per variable, each with a comment describing its constraints
 * (required/optional, type, allowed values) and a sensible placeholder.
 */
final class EnvExampleGenerator
{
    private const DEFAULT_HEADER = '# Generated by env-validator — the environment variables this app expects.';

    /**
     * @param array<string, string|array<int, mixed>> $rules
     */
    public function __construct(private readonly array $rules)
    {
    }

    /**
     * @param array<string, string|array<int, mixed>> $rules
     */
    public static function fromRules(array $rules): self
    {
        return new self($rules);
    }

    public function generate(?string $header = null): string
    {
        $lines = [$header ?? self::DEFAULT_HEADER, ''];

        foreach ($this->rules as $key => $ruleSet) {
            $rules = $this->normalize($ruleSet);

            $hint = $this->hint($rules);
            if ($hint !== '') {
                $lines[] = '# '.$hint;
            }

            $lines[] = $key.'='.$this->placeholder($rules);
            $lines[] = '';
        }

        return rtrim(implode("\n", $lines), "\n")."\n";
    }

    /**
     * @param string|array<int, mixed> $ruleSet
     *
     * @return array<int, string>
     */
    private function normalize(string|array $ruleSet): array
    {
        $parts = is_string($ruleSet) ? explode('|', $ruleSet) : $ruleSet;

        // Only string rules carry readable metadata; skip Rule objects/closures.
        return array_values(array_filter(
            array_map(static fn ($rule) => is_string($rule) ? $rule : null, $parts),
            static fn ($rule) => $rule !== null && $rule !== '',
        ));
    }

    /**
     * @param array<int, string> $rules
     */
    private function hint(array $rules): string
    {
        $required = false;
        $tail = [];

        foreach ($rules as $rule) {
            [$name, $args] = $this->split($rule);

            match ($name) {
                'required' => $required = true,
                'nullable', 'sometimes' => null,
                'boolean' => $tail[] = 'boolean (true/false)',
                'integer', 'int' => $tail[] = 'integer',
                'numeric' => $tail[] = 'number',
                'string' => $tail[] = 'string',
                'url' => $tail[] = 'URL',
                'email' => $tail[] = 'email',
                'ip' => $tail[] = 'IP address',
                'uuid' => $tail[] = 'UUID',
                'json' => $tail[] = 'JSON',
                'in' => $tail[] = 'one of: '.implode(', ', $args),
                'not_in' => $tail[] = 'not one of: '.implode(', ', $args),
                'between' => $tail[] = 'between '.($args[0] ?? '?').' and '.($args[1] ?? '?'),
                'min' => $tail[] = 'min '.($args[0] ?? ''),
                'max' => $tail[] = 'max '.($args[0] ?? ''),
                'digits' => $tail[] = ($args[0] ?? '').' digits',
                'starts_with' => $tail[] = 'starts with '.implode('/', $args),
                'ends_with' => $tail[] = 'ends with '.implode('/', $args),
                'regex' => $tail[] = 'matches a pattern',
                default => $tail[] = $name,
            };
        }

        return implode(' · ', array_merge([$required ? 'required' : 'optional'], $tail));
    }

    /**
     * @param array<int, string> $rules
     */
    private function placeholder(array $rules): string
    {
        foreach ($rules as $rule) {
            [$name, $args] = $this->split($rule);

            if ($name === 'in' && isset($args[0])) {
                return $args[0];
            }

            if ($name === 'boolean') {
                return 'false';
            }
        }

        return '';
    }

    /**
     * @return array{0: string, 1: array<int, string>}
     */
    private function split(string $rule): array
    {
        [$name, $params] = array_pad(explode(':', $rule, 2), 2, null);
        $args = $params === null || $params === '' ? [] : explode(',', $params);

        return [strtolower(trim((string) $name)), $args];
    }
}
